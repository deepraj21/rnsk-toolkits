export * from './core/index.js';

export function getAllTools() {
  return toolkits.flatMap((t) =>
    t.tools.map((toolDef) => ({
      name: toolDef.name,
      description: toolDef.description ?? toolDef.tool.description ?? '',
      tool: toolDef.tool,
      requiredAuth: toolDef.requiredAuth,
      scope: toolDef.scope,
      toolkitId: t.id,
      keywords: toolDef.keywords ?? [],
      category: t.category,
      toolkitDisplayName: t.displayName,
      toolkitShortDescription: t.shortDescription,
    })),
  );
}

export function registerAllTools(registry: {
  register: (
    name: string,
    description: string,
    tool: unknown,
    options?: {
      requiredAuth?: string;
      scope?: 'read' | 'write' | 'delete';
      toolkitId?: string;
      keywords?: string[];
      category?: string;
      toolkitDisplayName?: string;
      toolkitShortDescription?: string;
    },
  ) => void;
}) {
  for (const entry of getAllTools()) {
    registry.register(entry.name, entry.description, entry.tool, {
      requiredAuth: entry.requiredAuth,
      scope: entry.scope,
      toolkitId: entry.toolkitId,
      keywords: entry.keywords,
      category: entry.category,
      toolkitDisplayName: entry.toolkitDisplayName,
      toolkitShortDescription: entry.toolkitShortDescription,
    });
  }
}
